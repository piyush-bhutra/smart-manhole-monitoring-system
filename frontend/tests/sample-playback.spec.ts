import { expect, test } from '@playwright/test'

test('the animation is fully visible on entry at a laptop presentation viewport', async ({ page }) => {
  await page.setViewportSize({ width: 1366, height: 768 })
  await page.route('**/api/**', route => route.abort())
  await page.goto('/')
  await page.getByRole('tab', { name: 'Demo scenarios', exact: true }).click()
  const box = await page.getByTestId('manhole-visualizer').boundingBox()
  expect(box).not.toBeNull()
  expect(box!.y).toBeGreaterThan(0)
  expect(box!.y + box!.height).toBeLessThanOrEqual(768)
})

test('sample entry remains usable on initial API failure and playback never fetches or mutates API data', async ({ page }) => {
  const requests: string[] = []
  await page.route('**/api/**', route => { requests.push(route.request().method()); return route.abort() })
  await page.goto('/')
  await page.getByRole('tab', { name: 'Demo scenarios', exact: true }).click()
  const count = requests.length
  await expect(page.getByRole('heading', { name: 'Sample scenarios', exact: true })).toBeVisible()
  await expect(page.getByTestId('metric-safe')).toContainText('08')
  await expect(page.getByText('Monitoring API unavailable', { exact: true })).toHaveCount(0)
  await page.clock.install()
  await page.clock.fastForward(17000)
  await expect(page.getByTestId('manhole-visualizer')).toContainText('Methane elevated')
  await expect(page.getByTestId('metric-active')).toContainText('01')
  await page.getByRole('button', { name: 'Inspect MH-001', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Sample history')
  await expect(page.getByRole('dialog').getByRole('button', { name: /Acknowledge/ })).toBeDisabled()
  await page.getByRole('button', { name: 'Close node details' }).click()
  expect(requests).toHaveLength(count)
  expect(requests.every(method => method === 'GET')).toBe(true)
  await page.getByRole('tab', { name: 'Live', exact: true }).click()
  await expect(page.getByText('Monitoring API unavailable', { exact: true })).toBeVisible()
})

test('automatic playback holds completion and restart or scenario change starts a clean run', async ({ page }) => {
  await page.route('**/api/**', route => route.abort())
  await page.goto('/')
  await page.getByRole('tab', { name: 'Demo scenarios', exact: true }).click()
  await page.clock.install()
  await page.clock.fastForward(50000)
  await expect(page.getByTestId('sample-playback-status')).toContainText('Completed')
  await expect(page.getByTestId('metric-hazard')).toContainText('00')
  await expect(page.getByTestId('metric-active')).toContainText('01')
  await page.clock.fastForward(60000)
  await expect(page.getByTestId('sample-progress')).toHaveAttribute('aria-valuenow', '48')
  await page.getByRole('button', { name: 'Restart scenario', exact: true }).click()
  await expect(page.getByTestId('sample-progress')).toHaveAttribute('aria-valuenow', '0')
  await expect(page.getByTestId('metric-active')).toContainText('00')
  await page.getByLabel('Sample scenario', { exact: true }).selectOption('combined')
  await page.clock.fastForward(17000)
  const visual = page.getByTestId('manhole-visualizer')
  await expect(visual).toContainText('Methane elevated')
  await expect(visual).toContainText('Water overflow')
  await page.clock.fastForward(16000)
  await expect(visual).not.toContainText('Methane elevated')
  await expect(visual).toContainText('Water overflow')
  await page.getByLabel('Sample scenario', { exact: true }).selectOption('campus')
  await expect(page.getByTestId('metric-active')).toContainText('00')
  await page.clock.fastForward(33000)
  await expect(page.getByTestId('metric-hazard')).toContainText('03')
  await expect(page.getByTestId('metric-active')).toContainText('03')
  await expect(visual).toContainText('Cover displaced')
})

